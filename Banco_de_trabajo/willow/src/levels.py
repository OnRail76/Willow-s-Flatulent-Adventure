ROOMS = [R1, R2, R3, R4]
TYPES = {'B': 1, 'E': 2, 'L': 3}


def parse(scr, name):
    assert len(scr) == 20, (name, len(scr))
    rows = [r.ljust(30, ' ')[:30] for r in scr]
    for r in scr:
        assert len(r) <= 30, (name, r)
    plats, decos, ens = [], [], []
    wx = None
    for i, row in enumerate(rows):
        mr = i + 3
        c = 0
        while c < 30:
            ch = row[c]
            if ch == '=':
                s = c
                while c < 30 and row[c] == '=':
                    c += 1
                plats.append((mr, s + 1, c - s))
                continue
            if ch in 'wp':
                decos.append((mr, c + 1, 0 if ch == 'w' else 1))
            elif ch in TYPES:
                t = TYPES[ch]
                x = (c + 1) * 8
                if t == 3:
                    y = (mr + 1) * 8 - 32
                else:
                    y = (mr + 1) * 8 - 16
                ens.append((t, x, y))
            elif ch == 'W':
                wx = (c + 1) * 8
                assert mr == 22, name
            c += 1
    assert wx is not None, name
    # validate: inside the arena and standing on a platform or the floor
    for t, x, y in ens:
        w = 32 if t == 3 else 16
        assert 8 <= x and x + w <= 248, ('enemy inside wall', name, t, x)
        feet_row = (y + (32 if t == 3 else 16)) // 8   # map row under the feet
        for c in range(x // 8, (x + w) // 8):
            if feet_row == 23:
                continue
            under = rows[feet_row - 3][c - 1] if 1 <= c <= 30 else '|'
            if under != '=':
                print('  aviso %s: enemigo tipo %d en x=%d sin suelo completo (col %d)' % (name, t, x, c))
                break
    nreg = sum(1 for e in ens if e[0] != 3)
    assert nreg <= 6, name
    # check every enemy stands on something
    return plats, decos, ens, wx


out = ['; generated by levels.py - do not edit', 'level_table:']
for r in range(4):
    for s in range(5):
        out.append(' dw lvl_%d_%d' % (r, s))
for r, room in enumerate(ROOMS):
    for s, scr in enumerate(room):
        p, d, e, wx = parse(scr, '%d-%d' % (r + 1, s + 1))
        out.append('lvl_%d_%d:' % (r, s))
        out.append(' db %d' % len(p) + ''.join(', %d,%d,%d' % t for t in p))
        out.append(' db %d' % len(d) + ''.join(', %d,%d,%d' % t for t in d))
        out.append(' db %d' % len(e) + ''.join(', %d,%d,%d' % t for t in e))
        out.append(' db %d' % wx)
open(os.path.join(os.path.dirname(__file__), '..', 'build', 'levels.inc'), 'w').write('\n'.join(out) + '\n')
print('levels ok')
